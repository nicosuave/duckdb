pub fn find_dot_command(option: &str) -> Option<&'static DotCommandSpec> {
    let n = option.len();
    if n == 0 {
        return None;
    }
    for command in METADATA_COMMANDS {
        let match_size = if command.match_size == 0 {
            n
        } else {
            command.match_size
        };
        if n < match_size {
            continue;
        }
        if n <= command.command.len() && command.command.as_bytes()[..n] == option.as_bytes()[..n] {
            return Some(command);
        }
    }
    None
}

pub fn should_show_in_help(id: DotCommandId) -> bool {
    !matches!(
        id,
        DotCommandId::Comment
            | DotCommandId::Constant
            | DotCommandId::Cont
            | DotCommandId::ContSel
            | DotCommandId::Error
            | DotCommandId::Keyword
            | DotCommandId::Indices
    )
}

